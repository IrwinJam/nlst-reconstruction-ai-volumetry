def f(x, d=3):
    """round half up like papers do, unicode minus"""
    if x is None:
        return "NA"
    from decimal import Decimal, ROUND_HALF_UP
    q = Decimal(str(x)).quantize(Decimal(1).scaleb(-d), rounding=ROUND_HALF_UP)
    return f"{q:f}".replace("-", "−")


def ci(c, d=3):
    return f"{f(c[0], d)}, {f(c[1], d)}"


def pct(x, d=0):
    return f(100 * x, d)


def p_(x):
    if x is None or x != x:
        return "NA"
    return "<.001" if x < 0.001 else f"{x:.3f}".lstrip("0") if x < 0.01 else f"{x:.2f}".lstrip("0")


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


